<section id="why-distinction" aria-labelledby="ma-why-distinction-title">
	<h2 id="ma-why-distinction-title">Why the distinction matters</h2>
	<p>FLATLOCK and ACTIVESEAM are sometimes grouped together because both can produce low-profile joins for close-fitting knitted garments. They should not be treated as interchangeable in a tech pack, request for quotation or production approval.</p>
	<p>The machine platform, stitch formation, thread count and resulting seam appearance differ. If a buyer requests “flatlock/active seam” without defining which construction is required, suppliers may quote different operations while appearing to answer the same specification. That ambiguity can affect sampling, cost, visual consistency and how the seam behaves on the nominated fabric.</p>
	<p>The practical solution is to specify the seam function and required construction, then approve the result on the actual production fabric. A machine name alone is not a complete acceptance standard.</p>
</section>

<section id="industrial-flatlock" aria-labelledby="ma-industrial-flatlock-title">
	<h2 id="ma-industrial-flatlock-title">What is industrial FLATLOCK?</h2>
	<p>In cut-and-sew performance apparel, industrial FLATLOCK commonly refers to a flatseam construction made on a feed-off-the-arm flatseamer. A 4-needle, 6-thread configuration, commonly referenced as stitch type 607, is widely used for low-profile panel joining, although other flatseam configurations also exist.</p>
	<p>Yamato identifies its FD-62G series as a 4-needle, 6-thread feed-off-the-arm flatseamer. Published submodel applications include T-shirt sleeve closing, underwear crotch seams, lightweight knitted-fabric joins and T-shirt shoulder seams. The same series includes different cutting arrangements, needle distances and fabric-weight applications, so “Yamato FLATLOCK” does not by itself define every production setting.</p>
	<p>The fabric edges may overlap by a controlled amount according to the seam class, machine setup and application. Thread formations cover the join, producing a relatively flat construction without the conventional projecting seam allowance associated with many general assembly seams. This makes FLATLOCK useful where inside profile and prolonged skin contact are important.</p>

