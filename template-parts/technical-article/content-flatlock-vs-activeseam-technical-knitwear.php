<section id="merrow-activeseam" aria-labelledby="ma-merrow-activeseam-title">
	<h2 id="ma-merrow-activeseam-title">What is Merrow ACTIVESEAM?</h2>
	<p>Merrow describes the MB-4DFO 2.0 as an ACTIVESEAM flat-overlock platform and as an alternative to conventional FLATLOCK, INTERLOCK and OVERLOCK stitching. The official machine specification identifies 2 needles and a 2- or 3-thread configuration. ACTIVESEAM is therefore a distinct named system, not a generic term for every visually flat seam.</p>
	<p>The MB-4DFO platform can be configured around the material, thread and intended application. Merrow publishes multiple ACTIVESEAM variations at the platform level, but possession of the machine does not prove that every published variation is currently offered or used on a particular garment.</p>
	<p>Athletik Clothing currently uses the Merrow MB-4DFO 2.0 and works with both 2-thread and 3-thread configurations according to project requirements. The configuration for a specific style must still be confirmed during development; it should not be inferred from a general machine video or finished-garment photograph.</p>

