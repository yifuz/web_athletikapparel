<section id="sampling-and-qc" aria-labelledby="ma-pu-sampling-qc-title">
	<h2 id="ma-pu-sampling-qc-title">Sampling validation &amp; underwear QC checkpoints</h2>
	<p>Because performance underwear fits directly against skin under high tension, inspection criteria should mirror the real failure points of close-fitting knitwear. Across sampling and bulk production, our underwear quality plan aligns around five core checkpoints:</p>
	<ol>
		<li><strong>Fit &amp; measurements against the approved sample:</strong> Check relaxed and extended Points of Measure (POMs)—waistband width relaxed and stretched, front/back rise, thigh opening, inseam and pouch depth—against the graded specification in your <a href="<?php echo esc_url( home_url( '/technical-knitwear-tech-pack-guide/' ) ); ?>">tech pack</a>.</li>
		<li><strong>Pouch &amp; panel symmetry (including mesh placement):</strong> Verify left-to-right mirror alignment on contoured front pouches, gusset seams and ventilation mesh panels so the garment does not twist on the body.</li>
		<li><strong>Waistband attachment &amp; recovery:</strong> Inspect elastic join security, uniform gathering/tension distribution around the waist circumference, and recovery after repeated extension without wavy body fabric below the band.</li>
		<li><strong>Seam appearance &amp; elasticity for the specified construction:</strong> Audit <code>ISO 607</code> FLATLOCK, ACTIVESEAM and <code>ISO 605</code>/<code>ISO 406</code> COVERSTITCH joins across cross-seam intersections for skipped stitches, needle-cut elastane filaments, thread tension balance and seam pop under stretch.</li>
		<li><strong>Fabric stretch, recovery &amp; agreed testing alignment:</strong> Confirm incoming roll GSM, width and shade consistency, then verify agreed lab criteria—such as dimensional change after home laundering (<code>AATCC TM135</code> / <code>ISO 5077</code>), knit stretch and growth (<code>ASTM D2594</code>), colorfastness to washing, rubbing and perspiration, and pilling—before pre-shipment AQL inspection (<code>ISO 2859-1</code>).</li>
	</ol>
