				</tr>
			</thead>
			<tbody>
				<tr>
					<th scope="row">Crotch gussets, inseams &amp; tight body panels</th>
					<td>True <code>ISO 607</code> FLATLOCK (4-needle, 6-thread) or Merrow ACTIVESEAM</td>
					<td>Joins fabric panels without a thick upright internal seam ridge, minimizing skin friction and chafing under compression tension.</td>
					<td>State <code>ISO 607</code> or ACTIVESEAM explicitly; compare sew-offs on the bulk-intent fabric.</td>
